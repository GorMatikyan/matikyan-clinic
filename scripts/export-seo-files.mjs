#!/usr/bin/env node
// Pulls everything the SEO admin panel manages - sitemap.xml, robots.txt, active redirects, site
// settings, page-SEO overlays, and structured data - from the backend CMS and bakes it into the
// static build. matikyan-clinic is deployed as static files on cPanel with no server process of
// its own, so:
//   - sitemap.xml/robots.txt/.htaccess MUST be real files (redirects specifically must be real
//     Apache directives - a client-side-only redirect can't produce an actual HTTP 301 for crawlers).
//   - Settings/page-SEO/schema are baked into src/generated/*.json and statically imported by the
//     app, rather than fetched at runtime: this data barely changes, so there's no reason to pay
//     for a network round-trip to a separate backend host on every single page view. The tradeoff
//     is that changes to these need a rebuild+redeploy (the admin panel's "Deploy" button) to go
//     live - unlike the blog, which stays a live runtime fetch since it's expected to publish
//     instantly.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const CMS_API_BASE_URL = process.env.CMS_API_BASE_URL ?? "https://admin-matikyan.com";
const PUBLIC_DIR = path.resolve(fileURLToPath(new URL("../public", import.meta.url)));
const GENERATED_DIR = path.resolve(fileURLToPath(new URL("../src/generated", import.meta.url)));

// The real static routes of the site (mirrors the `routeChildren` array in src/app/routes.tsx).
// The backend's /sitemap.xml only knows about admin-managed page-SEO rows and blog posts - it has
// no idea the frontend even has an /about or /services/teeth-whitening route, so a sitemap built
// from that endpoint alone would miss almost the entire site. Keep this list in sync with
// routeChildren whenever a route is added/removed/renamed.
const STATIC_ROUTES = [
  "",
  "about",
  "doctors",
  "services",
  "faq",
  "blog",
  "contact",
  "warranty",
  "dental-tourism",
  "services/dental-cleaning-check-up",
  "services/teeth-whitening",
  "services/veneers",
  "services/dental-implants",
  "services/prosthetics-crowns",
  "services/root-canal-treatment",
  "services/orthodontics",
  "services/periodontal-treatment",
  "services/oral-surgery",
  "services/digital-diagnostics",
];

const REDIRECTS_BEGIN = "# BEGIN CMS REDIRECTS (generated by scripts/export-seo-files.mjs - do not edit by hand)";
const REDIRECTS_END = "# END CMS REDIRECTS";

async function fetchText(endpoint) {
  const url = `${CMS_API_BASE_URL}${endpoint}`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText} for ${url}`);
  }
  return response.text();
}

async function fetchJsonData(endpoint) {
  const body = JSON.parse(await fetchText(endpoint));
  return body.data;
}

async function exportFile(endpoint, filename) {
  try {
    const content = await fetchText(endpoint);
    await writeFile(path.join(PUBLIC_DIR, filename), content, "utf-8");
    console.log(`[export-seo-files] wrote ${filename} from ${CMS_API_BASE_URL}${endpoint}`);
  } catch (error) {
    console.warn(
      `[export-seo-files] could not fetch ${CMS_API_BASE_URL}${endpoint} (${error.message}). Keeping the existing public/${filename} as-is.`,
    );
  }
}

async function exportGeneratedJson(endpoint, filename, { unwrap = true } = {}) {
  try {
    const data = unwrap ? await fetchJsonData(endpoint) : JSON.parse(await fetchText(endpoint));
    await mkdir(GENERATED_DIR, { recursive: true });
    await writeFile(path.join(GENERATED_DIR, filename), JSON.stringify(data, null, 2) + "\n", "utf-8");
    console.log(`[export-seo-files] wrote src/generated/${filename} from ${CMS_API_BASE_URL}${endpoint}`);
  } catch (error) {
    console.warn(
      `[export-seo-files] could not fetch ${CMS_API_BASE_URL}${endpoint} (${error.message}). Keeping the existing src/generated/${filename} as-is.`,
    );
  }
}

function xmlEscape(value) {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

async function exportSitemap(preferredDomain, pageSeoEntries) {
  const origin = `https://${preferredDomain}`;
  const noindexByPath = new Map(pageSeoEntries.map((page) => [page.path, page.seoFields.robotsNoindex]));

  let blogPosts = [];
  try {
    const page = await fetchJsonData("/api/public/cms/blog-posts?size=1000");
    blogPosts = (page?.content ?? []).filter((post) => !post.seoFields.robotsNoindex);
  } catch (error) {
    console.warn(`[export-seo-files] could not fetch blog posts for sitemap (${error.message}). Sitemap will omit blog posts.`);
  }

  const staticUrls = STATIC_ROUTES.filter((route) => noindexByPath.get(`/${route}`) !== true).map(
    (route) => `${origin}/${route}`,
  );
  const blogUrls = blogPosts.map((post) => `${origin}/blog/${post.slug}`);

  // Any admin-managed page-SEO row for a path that isn't already a known static route (e.g. a
  // custom landing page created purely through the admin panel) still belongs in the sitemap.
  const extraAdminUrls = pageSeoEntries
    .filter((page) => !page.seoFields.robotsNoindex && !STATIC_ROUTES.includes(page.path.replace(/^\//, "")))
    .map((page) => `${origin}${page.path}`);

  const allUrls = [...new Set([...staticUrls, ...blogUrls, ...extraAdminUrls])];

  const xml = [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">`,
    ...allUrls.map((url) => `  <url>\n    <loc>${xmlEscape(url)}</loc>\n  </url>`),
    `</urlset>`,
    "",
  ].join("\n");

  await writeFile(path.join(PUBLIC_DIR, "sitemap.xml"), xml, "utf-8");
  console.log(`[export-seo-files] wrote sitemap.xml with ${allUrls.length} URL(s)`);
}

async function exportRedirectsIntoHtaccess() {
  const htaccessPath = path.join(PUBLIC_DIR, ".htaccess");

  let rules;
  try {
    rules = await fetchText("/api/public/cms/redirects/apache");
  } catch (error) {
    console.warn(
      `[export-seo-files] could not fetch redirects (${error.message}). Keeping public/.htaccess as-is.`,
    );
    return;
  }

  const block = [REDIRECTS_BEGIN, rules.trim(), REDIRECTS_END].join("\n");
  const existing = await readFile(htaccessPath, "utf-8");

  const beginIndex = existing.indexOf(REDIRECTS_BEGIN);
  const endIndex = existing.indexOf(REDIRECTS_END);

  let next;
  if (beginIndex !== -1 && endIndex !== -1) {
    next = existing.slice(0, beginIndex) + block + existing.slice(endIndex + REDIRECTS_END.length);
  } else {
    // First run: insert at the very top, ahead of the hand-written mod_rewrite rules.
    next = `${block}\n\n${existing}`;
  }

  await writeFile(htaccessPath, next, "utf-8");
  console.log(`[export-seo-files] wrote ${rules.trim().split("\n").filter(Boolean).length} redirect(s) into public/.htaccess`);
}

await exportFile("/api/public/cms/robots.txt", "robots.txt");
await exportRedirectsIntoHtaccess();

await exportGeneratedJson("/api/public/cms/settings", "settings.json");
await exportGeneratedJson("/api/public/cms/pages/all", "pages.json");
await exportGeneratedJson("/api/public/cms/settings/schema", "schema.json", { unwrap: false });

try {
  const settings = await fetchJsonData("/api/public/cms/settings");
  const pageSeoEntries = await fetchJsonData("/api/public/cms/pages/all");
  await exportSitemap(settings.preferredDomain, pageSeoEntries);
} catch (error) {
  console.warn(`[export-seo-files] could not build sitemap.xml (${error.message}). Keeping the existing public/sitemap.xml as-is.`);
}
